"""Kinetic ASS Subtitle Engine producing dynamic, retention-boosting captions.

Synthesizes Advanced SubStation Alpha (.ass) subtitles with word-level active highlighting,
bold typography (Montserrat/Arial Black 72pt), high-contrast outlines/shadows, and
platform-specific safe-zone margins (320px vertical padding).
"""

import logging
from pathlib import Path
from typing import Sequence

from src.core.types import SentenceSegment, WordSegment

logger = logging.getLogger(__name__)


def format_ass_time(seconds: float) -> str:
    """Format seconds into standard ASS timestamp (H:MM:SS.cc, centisecond precision)."""
    if seconds < 0.0:
        seconds = 0.0
    hours = int(seconds // 3600)
    minutes = int((seconds % 3600) // 60)
    secs = int(seconds % 60)
    centis = int(round((seconds - int(seconds)) * 100))
    if centis >= 100:
        centis = 99
    return f"{hours}:{minutes:02d}:{secs:02d}.{centis:02d}"


def generate_ass_header(is_vertical: bool = True, margin_v: int | None = None) -> str:
    """Construct ASS script info and style definition conforming to mobile safe-zones."""
    res_x = 1080 if is_vertical else 1920
    res_y = 1920 if is_vertical else 1080
    effective_margin_v = margin_v if margin_v is not None else (320 if is_vertical else 60)

    # Styling: Montserrat/Arial Black, 72pt, Bold, White fill (&H00FFFFFF&),
    # Outline 5px (&H00000000&), Shadow 2px, Alignment 2 (bottom center)
    return (
        "[Script Info]\n"
        "; Script generated by TeamTrau AutoEdit Kinetic Engine\n"
        "ScriptType: v4.00+\n"
        f"PlayResX: {res_x}\n"
        f"PlayResY: {res_y}\n"
        "ScaledBorderAndShadow: yes\n"
        "YCbCr Matrix: TV.709\n\n"
        "[V4+ Styles]\n"
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, "
        "BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, "
        "BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding\n"
        f"Style: KineticPop,Montserrat,72,&H00FFFFFF&,&H0000FFFF&,&H00000000&,&H00000000&,"
        f"-1,0,0,0,100,100,0,0,1,5,2,2,40,40,{effective_margin_v},1\n\n"
        "[Events]\n"
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n"
    )


def export_kinetic_ass(
    sentences: Sequence[SentenceSegment],
    output_path: Path,
    is_vertical: bool = True,
    margin_v: int | None = None,
    highlight_color: str = "&H0000FFFF&",
    base_color: str = "&H00FFFFFF&",
) -> Path:
    """Export spoken sentence segments to an animated kinetic .ass subtitle file.

    Illuminates active spoken words with highlight_color (default: electric yellow/cyan)
    during their exact word-level timing interval [start_time, end_time], while resetting
    surrounding words to base_color (white). Enforces platform safe zones (MarginV=320px).
    """
    output_path.parent.mkdir(parents=True, exist_ok=True)
    header = generate_ass_header(is_vertical=is_vertical, margin_v=margin_v)

    dialogue_lines: list[str] = []

    for sentence in sentences:
        words: list[WordSegment] = sentence.words if hasattr(sentence, "words") and sentence.words else []

        if not words:
            # Fallback for sentences without granular word-level boundary data
            t_start = format_ass_time(sentence.start_time)
            t_end = format_ass_time(sentence.end_time)
            clean_text = sentence.text.strip().replace("\n", " ")
            if clean_text:
                dialogue_lines.append(
                    f"Dialogue: 0,{t_start},{t_end},KineticPop,,0,0,0,,{clean_text}"
                )
            continue

        # Word-level active karaoke highlighting events
        for active_idx, active_word in enumerate(words):
            w_start = format_ass_time(active_word.start_time)
            w_end = format_ass_time(max(active_word.start_time + 0.05, active_word.end_time))

            # Assemble full sentence with active word highlighted
            tokens: list[str] = []
            for idx, w in enumerate(words):
                w_str = w.word.strip()
                if not w_str:
                    continue
                if idx == active_idx:
                    tokens.append(f"{{\\c{highlight_color}}}{w_str}{{\\c{base_color}}}")
                else:
                    tokens.append(w_str)

            line_text = " ".join(tokens)
            dialogue_lines.append(
                f"Dialogue: 0,{w_start},{w_end},KineticPop,,0,0,0,,{line_text}"
            )

    full_ass_content = header + "\n".join(dialogue_lines) + "\n"
    output_path.write_text(full_ass_content, encoding="utf-8")
    logger.info("Exported kinetic ASS subtitles with %d events to %s", len(dialogue_lines), output_path.name)
    return output_path
